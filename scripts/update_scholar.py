#!/usr/bin/env python3
"""Sync the site with the public Google Scholar profile.

Writes:
  _data/metrics.yml            total citations, h-index, i10-index
  _data/scholar_citations.yml  per-paper citation counts, keyed by slugified title
  _publications/<year>/*.md    a new entry for each Scholar paper the site does not have yet
                               (skipping ids listed in _data/scholar_ignore.yml)

Uses plain requests only. If Scholar refuses a request or the page layout changes, the script
leaves existing files untouched, so the site keeps the last known values.
"""
import datetime
import glob
import html
import json
import pathlib
import re
import sys
import time
import urllib.request

USER_ID = "ZpCrmOQAAAAJ"
ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "_data"
PUBS = ROOT / "_publications"
BASE = "https://scholar.google.com"
PROFILE_URL = f"{BASE}/citations?user={USER_ID}&hl=en&cstart=0&pagesize=100&sortby=pubdate"
MAX_NEW_PER_RUN = 5  # each new paper costs one extra request for its detail page


def fetch(url):
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (compatible; danielogen.github.io scholar sync)",
        "Accept-Language": "en-US,en;q=0.9",
    })
    with urllib.request.urlopen(req, timeout=30) as resp:
        return resp.read().decode("utf-8", errors="replace")


def text(fragment):
    return html.unescape(re.sub(r"<.*?>", "", fragment)).strip()


def slugify(title):
    # Mirrors Jekyll's `slugify` filter for ASCII titles, so Liquid can look the key up.
    return re.sub(r"[^0-9a-z]+", "-", title.lower()).strip("-")


def q(value):
    # JSON strings are valid double-quoted YAML scalars.
    return json.dumps(value, ensure_ascii=False)


def write_if_changed(path, content):
    if path.exists() and path.read_text() == content:
        return False
    path.write_text(content)
    return True


def parse_rows(page):
    rows = []
    for row in re.findall(r'<tr class="gsc_a_tr">(.*?)</tr>', page, re.S):
        title = re.search(r'class="gsc_a_at">(.*?)</a>', row, re.S)
        href = re.search(r'href="([^"]*citation_for_view=([^"&]+)[^"]*)"', row)
        if not title or not href:
            continue
        gray = re.findall(r'<div class="gs_gray">(.*?)</div>', row, re.S)
        venue = re.sub(r'<span class="gs_oph">.*?</span>', "", gray[1]) if len(gray) > 1 else ""
        cites = re.search(r'class="gsc_a_ac gs_ibl">(\d*)<', row)
        year = re.search(r'class="gsc_a_h gsc_a_hc gs_ibl">(\d{4})<', row)
        cid = href.group(2)
        rows.append({
            "id": cid,
            "title": text(title.group(1)),
            "authors": text(gray[0]) if gray else "",
            "venue": text(venue),
            "year": year.group(1) if year else "",
            "citations": int(cites.group(1)) if cites and cites.group(1) else 0,
            "url": f"{BASE}/citations?view_op=view_citation&hl=en&user={USER_ID}&citation_for_view={cid}",
        })
    return rows


def update_metrics(page):
    cells = re.findall(r'<td class="gsc_rsb_std">(\d+)</td>', page)
    if len(cells) < 6:
        print("Metrics table not found; keeping existing metrics.")
        return
    # Table order: citations (all, since), h-index (all, since), i10-index (all, since)
    content = (
        "# Generated by scripts/update_scholar.py (runs weekly in GitHub Actions).\n"
        "# Manual edits are fine; they are overwritten on the next successful update.\n"
        f"updated: {datetime.date.today().strftime('%b %Y')}\n"
        f"citations: {cells[0]}\n"
        f"h_index: {cells[2]}\n"
        f"i10_index: {cells[4]}\n"
    )
    if write_if_changed(DATA / "metrics.yml", content):
        print(f"Updated metrics: citations={cells[0]}, h-index={cells[2]}, i10-index={cells[4]}")


def update_citations(rows):
    best = {}
    for r in rows:
        key = slugify(r["title"])
        if key not in best or r["citations"] > best[key]["citations"]:
            best[key] = r
    lines = ["# Generated by scripts/update_scholar.py: per-paper Google Scholar citation counts.\n"]
    for key in sorted(best):
        r = best[key]
        lines.append(f"{q(key)}: {{ citations: {r['citations']}, url: {q(r['url'])} }}\n")
    if write_if_changed(DATA / "scholar_citations.yml", "".join(lines)):
        print(f"Updated per-paper citations for {len(best)} titles.")


def guess_type(venue):
    v = venue.lower()
    if "arxiv" in v:
        return "preprint"
    if any(k in v for k in ("journal", "transactions", "data in brief", "empirical software engineering", "letters", "review")):
        return "journal"
    return "conference"


def import_new(rows):
    have = set()
    for f in glob.glob(str(PUBS / "*" / "*.md")):
        m = re.search(r'^title:\s*"?(.*?)"?\s*$', pathlib.Path(f).read_text(), re.M)
        if m:
            have.add(slugify(m.group(1)))
    ignore_file = DATA / "scholar_ignore.yml"
    ignored = set(re.findall(r'"([^"]+)"', ignore_file.read_text())) if ignore_file.exists() else set()

    created = 0
    for r in rows:
        key = slugify(r["title"])
        if key in have or r["id"] in ignored or not r["year"]:
            continue
        if created >= MAX_NEW_PER_RUN:
            print("Reached the per-run import limit; remaining papers will be imported next run.")
            break

        authors = [a.strip() for a in r["authors"].split(",") if a.strip() and a.strip() != "..."]
        paper_link = None
        try:
            time.sleep(3)
            detail = fetch(r["url"])
            field = re.search(r'<div class="gsc_oci_field">Authors</div><div class="gsc_oci_value">(.*?)</div>', detail, re.S)
            if field:
                authors = [a.strip() for a in text(field.group(1)).split(",") if a.strip()]
            link = re.search(r'<a class="gsc_oci_title_link" href="([^"]+)"', detail)
            if link:
                paper_link = html.unescape(link.group(1))
        except Exception as exc:
            print(f"Could not fetch details for '{r['title']}' ({exc}); using the short author list.")
        if "Ogenrwot" in " ".join(authors):
            authors = ["Daniel Ogenrwot" if "Ogenrwot" in a else a for a in authors]

        ptype = guess_type(r["venue"])
        venue_short = f"arXiv {r['year']}" if ptype == "preprint" else ""
        out_dir = PUBS / r["year"]
        out_dir.mkdir(exist_ok=True)
        path = out_dir / f"scholar-{key[:60].rstrip('-')}.md"
        links = []
        if paper_link:
            links.append(f"  {'Preprint' if ptype == 'preprint' else 'Paper'}: {q(paper_link)}\n")
        links.append(f"  Scholar: {q(r['url'])}\n")
        path.write_text(
            "---\n"
            f"# Auto-imported from Google Scholar on {datetime.date.today()}. Review and enrich\n"
            "# (venue_short, abstract, topics, links), then delete the `auto_imported` line.\n"
            "auto_imported: true\n"
            f"title: {q(r['title'])}\n"
            f"date: {r['year']}-01-01 12:00:00 +0000\n"
            "selected: false\n"
            f"pub: {q(r['venue'])}\n"
            f"pub_date: {q(r['year'])}\n"
            f"type: {ptype}\n"
            + (f"venue_short: {q(venue_short)}\n" if venue_short else "")
            + "authors:\n" + "".join(f"  - {q(a)}\n" for a in authors)
            + "links:\n" + "".join(links)
            + "---\n"
        )
        have.add(key)
        created += 1
        print(f"Imported new publication: {r['title']} -> {path.relative_to(ROOT)}")


def main():
    try:
        page = fetch(PROFILE_URL)
    except Exception as exc:  # network error, HTTP 429, etc.
        print(f"Could not fetch Scholar profile ({exc}); keeping existing data.")
        return 0
    rows = parse_rows(page)
    if not rows:
        print("No publications found on the page (blocked or layout changed); keeping existing data.")
        return 0
    update_metrics(page)
    update_citations(rows)
    import_new(rows)
    return 0


if __name__ == "__main__":
    sys.exit(main())
